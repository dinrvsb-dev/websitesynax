out_dir = os.path.dirname(os.path.abspath(__file__))

def full(flow, prompt):
    return f"{prompt}. {STYLE}."

# ---------- README.md ----------
md = ["# Senarai Gambar SYNAX Flow", "",
      "Setiap prompt dah siap dengan gaya. Salin terus ke mana-mana AI image generator percuma.", "",
      "## Cara susun folder", "",
      "```", "gambar-synax/", "├── prasekolah/", "├── sekolah-rendah/", "└── spm/", "```", "",
      "- Nama fail **ikut lajur Fail** (contoh `pain-1.jpg`). Format JPG/PNG/WebP, lebar sekurang-kurangnya 1200px.",
      "- Ikut nisbah (1:1, 4:3, 16:9).",
      "- **Wajib** dulu. **Pilihan** kalau sempat.",
      "- Elak gambar ada tulisan, logo atau botol produk. Botol SYNAX sebenar aku letak sendiri.", ""]
for key, f in FLOWS.items():
    req = sum(1 for i in f["items"] if i[2])
    md += [f"## {f['title']}  →  folder `{key}/`", "", f"{req} wajib, {len(f['items'])-req} pilihan.", ""]
    for fn, ar, must, where, what, p in f["items"]:
        md += [f"### `{fn}.jpg` · {ar} · {'Wajib' if must else 'Pilihan'}", f"**Letak:** {where}  ", f"**Tunjuk:** {what}", "",
               "```", full(key, p), "```", ""]
open(os.path.join(out_dir, "README.md"), "w").write("\n".join(md))

# ---------- index.html (copy page) ----------
data = {k: {"title": v["title"], "items": [dict(fn=i[0], ar=i[1], must=i[2], where=i[3], what=i[4], prompt=full(k, i[5])) for i in v["items"]]} for k, v in FLOWS.items()}
tpl = open(os.path.join(out_dir, "template.html")).read()
open(os.path.join(out_dir, "index.html"), "w").write(tpl.replace("/*DATA*/null", json.dumps(data, ensure_ascii=False)))
print("ok", sum(len(v["items"]) for v in FLOWS.values()), "images")
